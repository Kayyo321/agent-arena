// schemagen compiles the repository's schema vocabulary to dependency-free Go.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"
)

type object = map[string]any

var out bytes.Buffer
var funcs []string
var models = map[string]string{}
var roots = map[string]string{"workflow": "Workflow", "project-settings": "ProjectSettings", "agent": "Profile", "message-envelope": "Envelope", "context-entry": "ContextEntry", "share-bundle": "ShareBundle"}

func main() {
	base := "."
	if len(os.Args) > 1 {
		base = os.Args[1]
	}
	out.WriteString("// Code generated by go run ./cmd/schemagen; DO NOT EDIT.\npackage contract\n\nimport (\"fmt\")\n\n")
	names := keys(roots)
	for _, name := range names {
		b, err := os.ReadFile(filepath.Join(base, "schemas", name+".schema.json"))
		must(err)
		var root object
		must(json.Unmarshal(b, &root))
		model(root, roots[name], root)
		f := compile(root, root)
		fmt.Fprintf(&out, "func Validate%s(data []byte) error { v,err:=decode(data); if err!=nil{return err}; return %s(v,\"$\") }\n", roots[name], f)
	}
	for _, n := range keys(models) {
		out.WriteString(models[n])
	}
	for _, f := range funcs {
		out.WriteString(f)
	}
	data, err := format.Source(out.Bytes())
	if err != nil {
		os.WriteFile("/tmp/arena-generated-invalid.go", out.Bytes(), 0600)
		panic(err)
	}
	must(os.WriteFile(filepath.Join(base, "internal", "contract", "generated.go"), data, 0644))
}
func must(e error) {
	if e != nil {
		panic(e)
	}
}
func keys[M ~map[string]V, V any](m M) []string {
	k := []string{}
	for n := range m {
		k = append(k, n)
	}
	sort.Strings(k)
	return k
}
func obj(v any) object { m, _ := v.(map[string]any); return m }
func list(v any) []any { a, _ := v.([]any); return a }
func contains(a any, s string) bool {
	for _, v := range list(a) {
		if v == s {
			return true
		}
	}
	return false
}
func ident(s string) string {
	var b strings.Builder
	up := true
	for _, c := range s {
		if !unicode.IsLetter(c) && !unicode.IsDigit(c) {
			up = true
			continue
		}
		if up {
			c = unicode.ToUpper(c)
			up = false
		}
		b.WriteRune(c)
	}
	return b.String()
}
func ref(s string, root object) object {
	v := any(root)
	for _, p := range strings.Split(strings.TrimPrefix(s, "#/"), "/") {
		v = obj(v)[p]
	}
	if obj(v) == nil {
		panic("unresolved ref " + s)
	}
	return obj(v)
}
func model(s object, n string, root object) string {
	if r, ok := s["$ref"].(string); ok {
		x := ident(strings.TrimPrefix(r, "#/$defs/"))
		if x != "Runtime" && x != "Actor" && x != "Workspace" {
			x = rootsName(root) + x
		}
		return model(ref(r, root), x, root)
	}
	if ts, ok := s["type"].([]any); ok {
		non := []any{}
		for _, t := range ts {
			if t != "null" {
				non = append(non, t)
			}
		}
		if len(non) == 1 {
			cp := object{}
			for k, v := range s {
				cp[k] = v
			}
			cp["type"] = non[0]
			return "*" + model(cp, n, root)
		}
		return "any"
	}
	if variants := list(s["oneOf"]); len(variants) > 0 {
		props := object{}
		counts := map[string]int{}
		allObjects := true
		for _, x := range variants {
			v := obj(x)
			if v["type"] != "object" {
				allObjects = false
				break
			}
			for k, p := range obj(v["properties"]) {
				props[k] = p
			}
			for _, k := range list(v["required"]) {
				counts[k.(string)]++
			}
		}
		if allObjects {
			required := []any{}
			for k, c := range counts {
				if c == len(variants) {
					required = append(required, k)
				}
			}
			return model(object{"type": "object", "properties": props, "required": required}, n, root)
		}
	}

	t, _ := s["type"].(string)
	if _, ok := s["const"]; ok && t == "" {
		switch s["const"].(type) {
		case string:
			t = "string"
		case float64:
			t = "integer"
		case bool:
			t = "boolean"
		case []any:
			t = "array"
			a := s["const"].([]any)
			if len(a) > 0 {
				if _, ok := a[0].(string); ok {
					return "[]string"
				}
			}
		}
	}
	if t == "" {
		if a := list(s["enum"]); len(a) > 0 {
			if _, ok := a[0].(string); ok {
				return "string"
			}
		}
		return "any"
	}
	switch t {
	case "string":
		return "string"
	case "integer":
		return "int"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "null":
		return "any"
	case "array":
		return "[]" + model(obj(s["items"]), n+"Item", root)
	case "object":
		props := obj(s["properties"])
		if len(props) == 0 {
			return "map[string]any"
		}
		if _, ok := models[n]; ok {
			return n
		}
		models[n] = ""
		var b strings.Builder
		fmt.Fprintf(&b, "type %s struct {\n", n)
		for _, k := range keys(props) {
			typ := model(obj(props[k]), n+ident(k), root)
			opt := !contains(s["required"], k)
			if opt && (typ == "int" || typ == "bool" || typ == "float64" || (obj(props[k])["type"] == "object" && !strings.HasPrefix(typ, "map[")) || (obj(props[k])["oneOf"] != nil && typ != "any")) {
				typ = "*" + typ
			}
			tag := k
			if opt {
				tag += ",omitempty"
			}
			fmt.Fprintf(&b, "%s %s `json:%q`\n", ident(k), typ, tag)
		}
		b.WriteString("}\n")
		models[n] = b.String()
		return n
	}
	panic(t)
}
func rootsName(root object) string {
	switch root["title"] {
	case "Agent Arena workflow":
		return "Workflow"
	case "Agent Arena project settings":
		return "ProjectSettings"
	case "Agent Arena profile":
		return "Profile"
	case "Agent Arena protocol message envelope":
		return "Envelope"
	default:
		return "ContextEntry"
	}
}
func literal(v any) string { b, e := json.Marshal(v); must(e); return fmt.Sprintf("jsonValue(%q)", b) }
func compile(s object, root object) string {
	index := len(funcs)
	funcs = append(funcs, "")
	name := fmt.Sprintf("check%d", index)
	var b strings.Builder
	fmt.Fprintf(&b, "func %s(v any,p string) error {\n", name)
	for k := range s {
		switch k {
		case "$schema", "title", "description", "default", "$defs", "$ref", "type", "const", "enum", "required", "properties", "additionalProperties", "items", "minItems", "maxItems", "uniqueItems", "minLength", "maxLength", "pattern", "format", "minimum", "maximum", "allOf", "anyOf", "oneOf", "not", "if", "then", "else":
		default:
			panic("unsupported schema keyword " + k)
		}
	}
	if r, ok := s["$ref"].(string); ok {
		f := compile(ref(r, root), root)
		fmt.Fprintf(&b, "if e:=%s(v,p);e!=nil{return e}\n", f)
	}
	if t, ok := s["type"]; ok {
		fmt.Fprintf(&b, "if !hasType(v,%s){return fmt.Errorf(\"%%s: expected %%v\",p,%s)}\n", literal(t), literal(t))
	}
	if c, ok := s["const"]; ok {
		fmt.Fprintf(&b, "if !equal(v,%s){return fmt.Errorf(\"%%s: expected constant %%v\",p,%s)}\n", literal(c), literal(c))
	}
	if a, ok := s["enum"]; ok {
		fmt.Fprintf(&b, "if !in(v,%s.([]any)){return fmt.Errorf(\"%%s: unsupported value %%v\",p,v)}\n", literal(a))
	}
	fmt.Fprintln(&b, "if m,ok:=v.(map[string]any);ok { _=m")
	for _, k := range list(s["required"]) {
		fmt.Fprintf(&b, "if _,ok:=m[%q];!ok{return fmt.Errorf(\"%%s: missing required field %s\",p)}\n", k, k)
	}
	for _, k := range keys(obj(s["properties"])) {
		f := compile(obj(obj(s["properties"])[k]), root)
		fmt.Fprintf(&b, "if x,ok:=m[%q];ok{if e:=%s(x,p+%q);e!=nil{return e}}\n", k, f, "/"+k)
	}
	if s["additionalProperties"] == false {
		allowed := []any{}
		for _, k := range keys(obj(s["properties"])) {
			allowed = append(allowed, k)
		}
		fmt.Fprintf(&b, "for k:=range m {if !in(k,%s.([]any)){return fmt.Errorf(\"%%s/%%s: unknown field\",p,k)}}\n", literal(allowed))
	}
	fmt.Fprintln(&b, "}")
	fmt.Fprintln(&b, "if a,ok:=v.([]any);ok { _=a")
	if x, ok := s["minItems"]; ok {
		fmt.Fprintf(&b, "if len(a)<%v{return fmt.Errorf(\"%%s: requires at least %v items\",p)}\n", x, x)
	}
	if x, ok := s["maxItems"]; ok {
		fmt.Fprintf(&b, "if len(a)>%v{return fmt.Errorf(\"%%s: allows at most %v items\",p)}\n", x, x)
	}
	if s["uniqueItems"] == true {
		b.WriteString("for i,x:=range a {for _,y:=range a[:i] {if equal(x,y){return fmt.Errorf(\"%s: duplicate array item\",p)}}}" + "\n")
	}
	if x := obj(s["items"]); x != nil {
		f := compile(x, root)
		fmt.Fprintf(&b, "for i,x:=range a {if e:=%s(x,fmt.Sprintf(\"%%s/%%d\",p,i));e!=nil{return e}}\n", f)
	}
	fmt.Fprintln(&b, "}")
	for _, k := range []string{"minLength", "maxLength", "pattern", "format", "minimum", "maximum"} {
		if x, ok := s[k]; ok {
			fmt.Fprintf(&b, "if e:=constraint(v,p,%q,%s);e!=nil{return e}\n", k, literal(x))
		}
	}
	for _, x := range list(s["allOf"]) {
		f := compile(obj(x), root)
		fmt.Fprintf(&b, "if e:=%s(v,p);e!=nil{return e}\n", f)
	}
	for _, k := range []string{"anyOf", "oneOf"} {
		if a := list(s[k]); len(a) > 0 {
			fmt.Fprintln(&b, "{ matches:=0")
			for _, x := range a {
				f := compile(obj(x), root)
				fmt.Fprintf(&b, "if %s(v,p)==nil{matches++}\n", f)
			}
			cond := "matches==0"
			if k == "oneOf" {
				cond = "matches!=1"
			}
			fmt.Fprintf(&b, "if %s{return fmt.Errorf(\"%%s: does not satisfy %s\",p)}}\n", cond, k)
		}
	}
	if x := obj(s["not"]); x != nil {
		f := compile(x, root)
		fmt.Fprintf(&b, "if %s(v,p)==nil{return fmt.Errorf(\"%%s: forbidden field combination\",p)}\n", f)
	}
	if x := obj(s["if"]); x != nil {
		f := compile(x, root)
		fmt.Fprintf(&b, "if %s(v,p)==nil {\n", f)
		if y := obj(s["then"]); y != nil {
			f = compile(y, root)
			fmt.Fprintf(&b, "if e:=%s(v,p);e!=nil{return e}\n", f)
		}
		fmt.Fprintln(&b, "} else {")
		if y := obj(s["else"]); y != nil {
			f = compile(y, root)
			fmt.Fprintf(&b, "if e:=%s(v,p);e!=nil{return e}\n", f)
		}
		fmt.Fprintln(&b, "}")
	}
	fmt.Fprintln(&b, "return nil\n}")
	funcs[index] = b.String()
	return name
}
